// Reference vectors for the circom-compatible Poseidon used by Privacy Pools v2, and LeanIMT membership paths
// in @zk-kit/lean-imt's proof format. Writes vectors.json and poseidon_spike/src/vectors.nr; `--check` fails if
// either file differs from a fresh generation.
import { execFileSync } from "node:child_process"
import { readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import { LeanIMT } from "@zk-kit/lean-imt"
import { poseidon1, poseidon2, poseidon4 } from "poseidon-lite"

const R = 21888242871839275222246405745257275088548364400416034343698204186575808495617n
const MAX_DEPTH = 18
const here = import.meta.dirname
const JSON_OUT = join(here, "vectors.json")
const NR_OUT = join(here, "..", "poseidon_spike", "src", "vectors.nr")

const X = 0x1234567890abcdef1234567890abcdef1234567890abcdef1234567890abcdn
const labelOf = (i: number) => (12345678901234567890123456789n * BigInt(i + 1)) % R

// Identical subtrees hash to identical nodes, so memoizing makes a 2^17-leaf tree cheap without changing the algorithm.
const memo = new Map<string, bigint>()
const h2 = (a: bigint, b: bigint): bigint => {
	const k = `${a}:${b}`
	let v = memo.get(k)
	if (v === undefined) {
		v = poseidon2([a, b])
		memo.set(k, v)
	}
	return v
}

interface Membership {
	name: string
	size: number
	leafIndex: number
	label: bigint
	root: bigint
	depth: number
	index: number
	siblings: bigint[]
}

/** Leaves 0..15 carry distinct labels; the rest repeat label 16, so most subtrees collapse under memoization. */
function membership(name: string, size: number, leafIndex: number): Membership {
	const labels = Array.from({ length: size }, (_, i) => labelOf(Math.min(i, 16)))
	const leaves = new Map<bigint, bigint>()
	const leafOf = (l: bigint) => leaves.get(l) ?? (leaves.set(l, poseidon1([l])).get(l) as bigint)
	const tree = new LeanIMT<bigint>(h2)
	tree.insertMany(labels.map(leafOf))
	const proof = tree.generateProof(leafIndex)
	if (proof.leaf !== poseidon1([labels[leafIndex] as bigint])) throw new Error(`${name}: leaf mismatch`)
	return {
		name,
		size,
		leafIndex,
		label: labels[leafIndex] as bigint,
		root: proof.root,
		depth: proof.siblings.length,
		index: proof.index,
		siblings: proof.siblings,
	}
}

function generate() {
	// Privacy Pools v2 deposit formulas (core-sdk NoteComputationService), with metadata 0.
	const owner = 0xa11ce5n
	const noteSecret = 0x5ec2e7n
	const depositSecret = 0xde9051n
	const tokenId = 0x1c7d4b196cb0c7b01d743fbc6116a902379c7238n
	const value = 1_000_000n
	const precommitment = poseidon4([poseidon2([owner, noteSecret]), tokenId, value, 0n])
	const label = poseidon2([precommitment, depositSecret])

	const memberships = [
		membership("single_leaf", 1, 0),
		membership("five_promoted", 5, 4),
		membership("five_inner", 5, 1),
		membership("eleven_promoted", 11, 10),
		membership("eleven_inner", 11, 3),
		membership("deep_first", 2 ** 17 + 1, 0),
		membership("deep_promoted", 2 ** 17 + 1, 2 ** 17),
	]
	const deep = memberships.find((m) => m.name === "deep_first")
	if (deep?.depth !== MAX_DEPTH) throw new Error(`deep_first has depth ${deep?.depth}, want ${MAX_DEPTH}`)

	return {
		hash1: [0n, 1n, X, R - 1n].map((x) => ({ inputs: [x], out: poseidon1([x]) })),
		hash2: [
			[0n, 0n],
			[1n, 2n],
			[X, R - 1n],
		].map((xs) => ({ inputs: xs, out: poseidon2(xs) })),
		pool: { precommitment, label, commitment: poseidon2([precommitment, label]), aspLeaf: poseidon1([label]) },
		memberships,
	}
}

type Vectors = ReturnType<typeof generate>

const hex = (v: bigint) => `0x${v.toString(16)}`

function toJson(v: Vectors): string {
	return `${JSON.stringify(v, (_, x) => (typeof x === "bigint" ? hex(x) : x), "\t")}\n`
}

function toNoir(v: Vectors): string {
	const lines = ["// Generated by vectors/gen.ts (poseidon-lite 0.3.0, @zk-kit/lean-imt 2.2.4). Do not edit.", ""]
	v.hash1.forEach((t, i) => {
		lines.push(`pub global HASH1_${i}_IN: Field = ${hex(t.inputs[0] as bigint)};`, `pub global HASH1_${i}_OUT: Field = ${hex(t.out)};`)
	})
	v.hash2.forEach((t, i) => {
		lines.push(`pub global HASH2_${i}_IN: [Field; 2] = [${t.inputs.map(hex).join(", ")}];`, `pub global HASH2_${i}_OUT: Field = ${hex(t.out)};`)
	})
	lines.push(
		`pub global POOL_PRECOMMITMENT: Field = ${hex(v.pool.precommitment)};`,
		`pub global POOL_LABEL: Field = ${hex(v.pool.label)};`,
		`pub global POOL_COMMITMENT: Field = ${hex(v.pool.commitment)};`,
		`pub global POOL_ASP_LEAF: Field = ${hex(v.pool.aspLeaf)};`,
		"",
		"pub struct Membership {",
		"    pub label: Field,",
		"    pub root: Field,",
		"    pub depth: u32,",
		"    pub index: u32,",
		`    pub siblings: [Field; ${MAX_DEPTH}],`,
		"}",
		"",
	)
	for (const m of v.memberships) {
		const padded = [...m.siblings, ...Array(MAX_DEPTH - m.siblings.length).fill(0n)].map(hex)
		lines.push(
			`// ${m.size} leaves, leaf ${m.leafIndex}.`,
			`pub global ${m.name.toUpperCase()}: Membership = Membership {`,
			`    label: ${hex(m.label)},`,
			`    root: ${hex(m.root)},`,
			`    depth: ${m.depth},`,
			`    index: ${m.index},`,
			`    siblings: [${padded.join(", ")}],`,
			"};",
			"",
		)
	}
	return lines.join("\n")
}

// nargo fmt re-wraps the generated Noir, so the check ignores layout: whitespace and trailing commas.
const normalize = (text: string) => text.replace(/\s+/g, "").replace(/,([\]}])/g, "$1")

const v = generate()
const outputs: [string, string][] = [
	[JSON_OUT, toJson(v)],
	[NR_OUT, toNoir(v)],
]
if (process.argv.includes("--check")) {
	const stale = outputs.filter(([path, text]) => {
		try {
			return normalize(readFileSync(path, "utf8")) !== normalize(text)
		} catch {
			return true
		}
	})
	if (stale.length > 0) {
		console.error(`stale vectors: ${stale.map(([p]) => p).join(", ")}; run \`bun run vectors\``)
		process.exit(1)
	}
	console.log("vectors up to date")
} else {
	for (const [path, text] of outputs) writeFileSync(path, text)
	execFileSync("sh", [join(here, "..", "scripts", "tool.sh"), "aztec-nargo", "fmt"], { cwd: join(here, ".."), stdio: "inherit" })
	console.log(`wrote ${outputs.length} files; ${v.memberships.map((m) => `${m.name}: depth ${m.depth} index ${m.index}`).join("; ")}`)
}
