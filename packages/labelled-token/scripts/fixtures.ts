/**
 * The LeanIMT trees the TXE suite checks spends against, rendered from @pp/bridge-spec into
 * `src/test/paths.nr` of the token crate. Every path is verified against its root before it is written.
 *
 *   fixtures.ts           write src/test/paths.nr
 *   fixtures.ts --check   fail if it differs from a fresh render (about 30 s: the depth-18 tree)
 */
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"
import { aspLeaf, assertLeanImtMember, buildLeanImt, type LabelPath } from "@pp/bridge-spec"

export const pathsFile = join(dirname(fileURLToPath(import.meta.url)), "../../../contracts/bridge/aztec/labelled_token/src/test/paths.nr")

interface Tree {
	name: string
	doc: string
	labels: bigint[]
	/** The labels whose paths are rendered, by leaf index. */
	picks: number[]
}

// `L` and `K` are the labels the TXE suite mints (`test/utils.nr`).
const L = 0x1abe1n
const K = 0x2abe1n
const POOL = [L, K, 0x3abe1n, 0x4abe1n, 0x5abe1n]
// Past 2^17 leaves the first leaf needs 18 siblings, the circuit's maximum.
const DEEP_SIZE = 2 ** 17 + 1

const TREES: Tree[] = [
	{
		name: "POOL",
		doc: "Five pool labels: the first four at depth 3, the fifth promoted to depth 1.",
		labels: POOL,
		picks: [0, 1, 2, 3, 4],
	},
	{ name: "BIRTH", doc: "A birth label and `POOL_LABELS[0]`, both at depth 1.", labels: [0xb1abe1n, L], picks: [0, 1] },
	{ name: "SOLO", doc: "One label alone: the root is its leaf, the path has depth 0.", labels: [0x6abe1n], picks: [0] },
	{
		name: "DEEP",
		doc: `Labels 1 to ${DEEP_SIZE}: the first at depth 18, the last promoted to depth 1.`,
		labels: Array.from({ length: DEEP_SIZE }, (_, i) => BigInt(i + 1)),
		picks: [0, DEEP_SIZE - 1],
	},
]

const hex = (x: bigint) => `0x${x.toString(16)}`
const path = (p: LabelPath) => `LabelPath { index: ${p.index}, depth: ${p.depth}, siblings: [${p.siblings.map(hex).join(", ")}] }`

function renderTree(t: Tree): string {
	const tree = buildLeanImt(t.labels.map(aspLeaf))
	const labels = t.picks.map((i) => t.labels[i] as bigint)
	const paths = t.picks.map((i) => tree.path(i))
	for (const [i, p] of paths.entries()) assertLeanImtMember(aspLeaf(labels[i] as bigint), p, tree.root)
	const n = t.picks.length
	return [
		`/// ${t.doc}`,
		`pub global ${t.name}_ROOT: Field = ${hex(tree.root)};`,
		`pub global ${t.name}_LABELS: [Field; ${n}] = [${labels.map(hex).join(", ")}];`,
		`pub global ${t.name}_PATHS: [LabelPath; ${n}] = [`,
		...paths.map((p) => `    ${path(p)},`),
		"];",
	].join("\n")
}

export function renderPaths(): string {
	const header = [
		"// Generated by `bun run --cwd packages/labelled-token fixtures` from @pp/bridge-spec; never edit.",
		"use asp_registry::label_check::LabelPath;",
	]
	return `${[header.join("\n"), ...TREES.map(renderTree)].join("\n\n")}\n`
}

if (import.meta.main) {
	const fresh = renderPaths()
	if (process.argv[2] === "--check") {
		if (readFileSync(pathsFile, "utf8") !== fresh) {
			console.error("✖ src/test/paths.nr is stale: run `bun run --cwd packages/labelled-token fixtures`")
			process.exit(1)
		}
		console.log("✔ src/test/paths.nr matches a fresh render")
	} else {
		writeFileSync(pathsFile, fresh)
	}
}
