import { readFileSync } from "node:fs"
import { join } from "node:path"
import { describe, expect, test } from "vitest"

type RawFunction = { name: string; abi: { parameters: { name: string }[] } }

const artifact = JSON.parse(
	readFileSync(
		join(import.meta.dirname, "../../../contracts/bridge/aztec/labelled_token/target/labelled_token-LabelledToken.json"),
		"utf8",
	),
) as { functions: RawFunction[] }

const DECLARED = [
	"balance_of_private",
	"balance_of_public",
	"burn_for_exit",
	"burn_public_for_exit",
	"constructor",
	"debit_for_shield",
	"decimals",
	"finish_unshield",
	"mint_from_bridge",
	"name",
	"private_balances_by_label",
	"private_notes_by_label",
	"shield",
	"symbol",
	"transfer_private",
	"transfer_public",
	"unshield",
]
// Generated by the #[aztec] macro for every contract.
const GENERATED = ["offchain_receive", "public_dispatch", "sync_state"]

const params = (f: RawFunction): string[] => f.abi.parameters.map((p) => p.name)

describe("contract surface", () => {
	test("exposes exactly the declared functions and the macro's own", () => {
		expect(artifact.functions.map((f) => f.name).sort()).toEqual([...DECLARED, ...GENERATED].sort())
	})

	test("only the constructor sets the registry", () => {
		expect(artifact.functions.filter((f) => params(f).includes("registry")).map((f) => f.name)).toEqual(["constructor"])
	})

	// aztec-nr's generated call stubs keep a local named `offset` and serialize it in place of a
	// parameter of that name, so every Noir caller would pass the wrong value.
	test("no parameter is named offset", () => {
		expect(artifact.functions.filter((f) => params(f).includes("offset")).map((f) => f.name)).toEqual([])
	})
})
